CREATE OR REPLACE FUNCTION public.capture_lead(p_nome text, p_email text, p_cidade text, p_telefone text, p_possui_formacao_superior boolean, p_area_formacao text, p_empresa text, p_cargo text, p_pretende_pos text)
 RETURNS leads
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_nome text := trim(coalesce(p_nome, ''));
  v_email citext := lower(trim(coalesce(p_email, '')));
  v_cidade text := nullif(trim(coalesce(p_cidade, '')), '');
  v_telefone text := regexp_replace(coalesce(p_telefone, ''), '\D', '', 'g');
  v_area_formacao text := trim(coalesce(p_area_formacao, ''));
  v_empresa text := trim(coalesce(p_empresa, ''));
  v_cargo text := trim(coalesce(p_cargo, ''));
  v_pretende_pos text := trim(coalesce(p_pretende_pos, ''));
  v_lead public.leads;
begin
  if v_nome = '' then
    raise exception 'Nome é obrigatório.';
  end if;

  if v_email = '' or v_email !~* '^[A-Z0-9._%+\-]+@[A-Z0-9.\-]+\.[A-Z]{2,}$' then
    raise exception 'E-mail inválido.';
  end if;

  if length(v_telefone) < 10 or length(v_telefone) > 13 then
    raise exception 'Telefone inválido.';
  end if;

  if p_possui_formacao_superior is null then
    raise exception 'Formação superior é obrigatória.';
  end if;

  if v_area_formacao = '' then
    raise exception 'Área de formação é obrigatória.';
  end if;

  if v_empresa = '' then
    raise exception 'Empresa é obrigatória.';
  end if;

  if v_cargo = '' then
    raise exception 'Cargo é obrigatório.';
  end if;

  if v_pretende_pos not in ('sim_agora', 'sim_depois', 'nao') then
    raise exception 'Valor inválido para pretende_pos.';
  end if;

  insert into public.leads (
    nome,
    email,
    cidade,
    telefone,
    possui_formacao_superior,
    area_formacao,
    empresa,
    cargo,
    pretende_pos
  )
  values (
    v_nome,
    v_email,
    v_cidade,
    v_telefone,
    p_possui_formacao_superior,
    v_area_formacao,
    v_empresa,
    v_cargo,
    v_pretende_pos
  )
  on conflict (email) do update
  set
    nome = excluded.nome,
    cidade = excluded.cidade,
    telefone = excluded.telefone,
    possui_formacao_superior = excluded.possui_formacao_superior,
    area_formacao = excluded.area_formacao,
    empresa = excluded.empresa,
    cargo = excluded.cargo,
    pretende_pos = excluded.pretende_pos
  returning * into v_lead;

  return v_lead;
end;
$function$;

CREATE OR REPLACE FUNCTION public.list_leads_admin()
 RETURNS TABLE(id bigint, created_at timestamp with time zone, nome text, email citext, cidade text, telefone text, possui_formacao_superior boolean, area_formacao text, empresa text, cargo text, pretende_pos text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if not public.is_admin() then
    raise exception 'Acesso negado.';
  end if;

  return query
  select
    l.id,
    l.created_at,
    l.nome,
    l.email::citext,
    l.cidade,
    l.telefone,
    l.possui_formacao_superior,
    l.area_formacao,
    l.empresa,
    l.cargo,
    l.pretende_pos
  from public.leads l
  order by l.created_at desc;
end;
$function$;
